def walk(node, path, out):
    if not node.variations:
        out.append(path); return
    for v in node.variations:
        walk(v, path + [v], out)


def build_course(meta):
    g = chess.pgn.read_game(open(os.path.join(HERE, 'openings', meta['file'])))
    if g.errors:
        sys.exit(f"{meta['file']}: {g.errors}")
    side = g.headers.get('Side', 'w')
    paths = []
    walk(g, [], paths)
    lines = []
    names = {}
    for p in paths:
        b = g.board()
        moves = []
        label = None
        devs = []
        for n in p:
            c = (n.comment or '').strip()
            if c.startswith('@'):
                label = c[1:].strip(); c = ''
            if n.parent.variations and n.parent.variations[0] is not n:
                devs.append(len(moves))
            moves.append(dict(san=b.san(n.move), uci=n.move.uci(), c=c or None))
            b.push(n.move)
        if len(moves) < 4:
            continue
        # убираем пустые комментарии
        for m in moves:
            if not m['c']:
                del m['c']
        name = label or 'Главная линия'
        names.setdefault(name, []).append(len(lines))
        sans = [m['san'] for m in moves]
        prev = []
        for i, s in enumerate(sans[:14]):
            prev.append((f'{i // 2 + 1}.' if i % 2 == 0 else '') + s)
        lid = meta['id'] + ':' + hashlib.sha1(' '.join(m['uci'] for m in moves).encode()).hexdigest()[:8]
        lines.append(dict(id=lid, name=name, moves=moves, preview=' '.join(prev) + (' …' if len(sans) > 14 else ''), devs=devs))
    # одинаковые имена -> добавляем отличающийся ход
    for name, idxs in names.items():
        if len(idxs) < 2:
            continue
        for k, i in enumerate(idxs):
            ln = lines[i]
            d = ln['devs'][-1] if ln['devs'] else None
            if d is None or k == 0:
                continue
            m = ln['moves'][d]
            ln['name'] = f"{name} — {d // 2 + 1}{'.' if d % 2 == 0 else '...'}{m['san']}"
    for ln in lines:
        del ln['devs']
    # главная линия первой, остальные — как в PGN
    return dict(id=meta['id'], title=meta['title'], tagline=meta['tagline'], side=side, intro=meta['intro'], ideas=meta['ideas'], lines=lines)


